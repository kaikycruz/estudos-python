filmsTuple = ("Inception", "The Dark Knight", "Interstellar", "Parasite", "Joker")
print(type(filmsTuple))  # retorna o tipo da variável (tuple)
print(filmsTuple[:2])  # retorna os dois primeiros elementos da tupla
print(filmsTuple[-1])  # retorna o último elemento da tupla
print(filmsTuple[:3])  # retorna os três primeiros elementos da tupla
print(filmsTuple[2:])  # retorna os elementos a partir do índice 2 até o final da tupla

print(filmsTuple.index("Interstellar"))  # retorna o índice do elemento "Interstellar"
